// Home: the one answer, and the evidence behind it.
//
// The verdict is never behind a menu. If somebody opens this app it is because
// they want to know whether to go inside, and that has to be the first thing
// they see — with the measurements that produced it one tap away, because a
// verdict nobody can interrogate is a verdict nobody should trust.

import { store } from '../state.js';
import {
  el, panel, readout, readoutGrid, button, pill, notice, icon, relativeTime, setChildren,} from '../ui/dom.js';
import { VERDICTS, SOILS } from '../core/library.js';
import { empiricalPeriod, ShearBuilding, fundamentalPeriod } from '../core/structures.js';
import { crossCheckedPeriod } from '../core/spectrum.js';
import { Haptics } from '../platform.js';

export function renderHome({ node, navigate, rerender, onCleanup }) {
  const building = store.selectedBuilding;
  const container = el('.stack', { style: { gap: '20px' } });

  if (!building) {
    return el('.empty', {}, [
      el('h2.title', { text: 'No building yet' }),
      button('Go to the library', () => navigate('library')),
    ]);
  }

  const assessment = store.latestAssessment;
  const verdict = VERDICTS[assessment?.verdict ?? 'unknown'];

  // ── Building header ──────────────────────────────────────────────────────
  container.append(el('.hstack', {}, [
    el('.stack-tight', { style: { flex: '1', minWidth: '0' } }, [
      el('h2.title', { text: building.name }),
      el('p.caption', {
        text: `${building.storeyCount} storeys · ${labelForMaterial(building.material)}`,
      }),
    ]),
    el('button.icon-button', {
      type: 'button',
      'aria-label': 'Switch building',
      on: { click: () => navigate('library') },
    }, [icon('building', { size: 20 })]),
  ]));

  // ── The verdict ──────────────────────────────────────────────────────────
  if (assessment) {
    container.append(el(`button.placard.${verdict.tone}`, {
      type: 'button',
      dataset: { tour: 'verdict' },
      style: { width: '100%', textAlign: 'left' },
      on: { click: () => navigate('assess') },
    }, [
      el('.verdict', { text: verdict.label }),
      el('.meaning', { text: verdict.meaning }),
      el('.caption', {
        text: `Assessed ${relativeTime(assessment.createdAt)}`
          + ` · confidence ${Math.round((assessment.confidence ?? 0) * 100)}%`,
      }),
    ]));

    if (Number.isFinite(assessment.periodChangePercent)) {
      container.append(panel(null, [
        readoutGrid([
          readout('Period change',
            `${assessment.periodChangePercent >= 0 ? '+' : ''}${assessment.periodChangePercent.toFixed(1)}`,
            {
              unit: '%',
              large: true,
              tint: Math.abs(assessment.periodChangePercent) < 3
                ? 'var(--text-primary)'
                : `var(--verdict-${verdict.tone})`,
            }),
          readout('Peak drift', (assessment.maximumDrift * 100).toFixed(2), { unit: '%' }),
        ]),
      ]));
    }
  } else {
    container.append(el('.placard.grey', {}, [
      el('.verdict', { text: VERDICTS.unknown.label }),
      el('.meaning', {
        text: 'No event has been recorded for this building yet, so there is nothing to '
          + 'assess. The baseline below is what any future assessment is compared against.',
      }),
    ]));
  }

  // ── Baseline ─────────────────────────────────────────────────────────────
  const model = ShearBuilding.from(building);
  const expected = empiricalPeriod(building);
  const modelled = fundamentalPeriod(model);

  const baselinePanel = panel('Baseline', [
    readoutGrid([
      readout('Measured period', '—', { unit: 's', large: true }),
      readout('Expected for this type', expected.toFixed(2), { unit: 's' }),
      readout('Modelled period', modelled.toFixed(2), { unit: 's' }),
      readout('Structure temperature', '—', { unit: '°C' }),
    ]),
    el('p.caption', {
      text: 'The expected period comes from the building codes — a regression through '
        + 'measured buildings of this height and system. When the measurement disagrees '
        + 'with it, the measurement wins: it was taken from this building.',
    }),
  ], { iconName: 'wave' });
  container.append(baselinePanel);

  // ── Sensor ───────────────────────────────────────────────────────────────
  const sensorPanel = panel('Sensor', [], {
    iconName: 'sensor',
    trailing: pill('Simulated node', 'violet'),
  });
  container.append(sensorPanel);

  container.append(notice('info', 'Simulated node',
    'Everything you see is generated by a physically realistic simulation — real P and '
    + 'S waves, a real noise floor, real actuator timing. Connect a node to replace it '
    + 'with live data.',
    button('Node diagnostics', () => navigate('node'), { kind: 'quiet' })));

  // ── Quick actions ────────────────────────────────────────────────────────
  container.append(el('.stack', {}, [
    button('Simulate an earthquake', () => {
      const quake = store.get('earthquakes')[0];
      const { warningSeconds, distanceKm } = node.injectEarthquake(quake, 30);
      Haptics.notification('WARNING');
      window.seismic.beginEvent({
        warningSeconds, distanceKm, magnitude: quake.magnitude,
      });
    }, { block: true, iconName: 'bolt' }),
    button('Run a drill', () => {
      window.seismic.beginEvent({ warningSeconds: 8, isDrill: true });
    }, { kind: 'secondary', block: true }),
  ]));

  // ── Live values ──────────────────────────────────────────────────────────
  //
  // Only this screen's live numbers subscribe to the node; the rest of the
  // screen is static and is not rebuilt when a sample arrives.
  let lastMeasured = 0;
  const unsubscribe = store.subscribe('node', (snapshot) => {
    if (!snapshot || !container.isConnected) return;

    const temperature = snapshot.telemetry.structureTemperature;
    baselinePanel.querySelectorAll('.readout-value')[3].firstChild.textContent =
      temperature.toFixed(1);

    // Re-measuring the period is a full spectral pass. Once a second is far
    // more often than a building's period meaningfully changes, and twenty
    // times a second would be most of a phone's battery.
    const now = Date.now();
    // Twenty seconds minimum.
    //
    // Welch splits the record into segments, so the lowest frequency it can
    // resolve is set by the segment length, not the total. Four seconds of data
    // cannot see a 1.1 Hz mode at all — it reported 0.09 s instead of 0.89,
    // which is not a slightly wrong answer but a confident wrong one. Twenty
    // seconds gives roughly twenty cycles of a one-second building.
    const enough = snapshot.recent.sampleRate * 20;
    if (now - lastMeasured > 1000 && snapshot.recent.count > enough) {
      lastMeasured = now;
      const check = crossCheckedPeriod(snapshot.recent.x);
      if (check.consensus) {
        baselinePanel.querySelectorAll('.readout-value')[0].firstChild.textContent =
          check.consensus.toFixed(3);
        node.measuredPeriod = check.consensus;
      }
    } else if (snapshot.recent.count <= enough) {
      // Says what it is doing rather than showing a dash. A blank readout looks
      // broken; "measuring" is the truth and sets the expectation.
      const seconds = Math.ceil((enough - snapshot.recent.count)
        / Math.max(snapshot.recent.sampleRate, 1));
      baselinePanel.querySelectorAll('.readout-value')[0].firstChild.textContent =
        `${seconds}s`;
    }

    setChildren(sensorPanel, [
      el('.panel-header', {}, [
        el('.panel-label', {}, [icon('sensor', { size: 15 }), 'Sensor']),
        pill(snapshot.isSimulated ? 'Simulated node' : 'Live node', 'violet'),
      ]),
      readoutGrid([
        readout('State', capitalise(snapshot.state)),
        readout('Trigger ratio', lastRatio(snapshot).toFixed(2)),
        readout('Ambient', snapshot.recent.x.rms.toFixed(4), { unit: 'm/s²' }),
        readout('Supply', snapshot.telemetry.supplyVolts.toFixed(2), { unit: 'V' }),
      ]),
    ]);
  });
  onCleanup(unsubscribe);

  // ── Context ──────────────────────────────────────────────────────────────
  container.append(panel('This building', [
    readoutGrid([
      readout('Height', String(building.height), { unit: 'm' }),
      readout('Built', building.yearBuilt ? String(building.yearBuilt) : '—'),
      readout('Ground', SOILS[building.soil]?.label ?? 'Unknown'),
      readout('Retrofit', capitalise(building.retrofit ?? 'none')),
    ]),
    building.notes && el('p.body.prose', { text: building.notes }),
  ], { iconName: 'building' }));

  return container;
}

function lastRatio(snapshot) {
  const samples = snapshot.ratio?.samples;
  const value = samples?.length ? samples[samples.length - 1] : 1;
  return Number.isFinite(value) ? value : 1;
}

function capitalise(text) {
  const value = String(text ?? '');
  return value.charAt(0).toUpperCase() + value.slice(1);
}

function labelForMaterial(key) {
  return {
    reinforcedConcrete: 'Reinforced concrete',
    steel: 'Steel',
    timber: 'Timber',
    masonry: 'Masonry',
    unreinforcedMasonry: 'Unreinforced masonry',
    hybrid: 'Hybrid',
  }[key] ?? 'Unknown material';
}
